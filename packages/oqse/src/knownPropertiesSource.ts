/**
 * The source of `knownProperties.generated.ts`, from the item schemas (build time and test).
 */

import { propertyPaths } from './propertyPaths';

type SchemaLike = { _zod: { def: any } };

export function knownPropertiesSource(itemUnion: SchemaLike): string {
  const byType: Record<string, string[]> = {};
  for (const option of itemUnion._zod.def.options as SchemaLike[]) {
    const type = option._zod.def.shape.type._zod.def.values[0] as string;
    byType[type] = propertyPaths(option);
  }
  const types = Object.keys(byType).sort();
  // Properties every type has (the common item properties) are written once.
  const common = byType[types[0]].filter((path) => types.every((type) => byType[type].includes(path)));
  const lines = types.map((type) => `  ${JSON.stringify(type)}: ${JSON.stringify(byType[type].filter((path) => !common.includes(path)))},`);
  return [
    '// Generated by scripts/generate-known-properties.ts from the item schemas – do not edit.',
    '// The property paths each official item type defines in this OQSE version (lists and maps',
    '// are passed through), for `mustUnderstand` (OQSE "Must-Understand Properties").',
    '',
    `const COMMON: readonly string[] = ${JSON.stringify(common)};`,
    '',
    'const BY_TYPE: Record<string, readonly string[]> = {',
    ...lines,
    '};',
    '',
    '/** Property paths per official item type (the common item properties included). */',
    'export const KNOWN_ITEM_PROPERTIES: Readonly<Record<string, readonly string[]>> = Object.fromEntries(',
    '  Object.entries(BY_TYPE).map(([type, paths]) => [type, [...COMMON, ...paths]]),',
    ');',
    '',
  ].join('\n');
}
